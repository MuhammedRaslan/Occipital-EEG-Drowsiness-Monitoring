"""Table bodies for the supplementary material, from results/*.json.

Each table is written as a LaTeX fragment (the rows between \\midrule and
\\bottomrule) to supplementary/tables/, and supplementary.tex inputs it, so no
value in the supplementary is typed by hand.

  s1_seed.tex, s1_dd.tex   per-driver metrics (Table S1)
  s3_grid.tex              DD-Database label-window grid (Table S2)
  s4_filter.tex            filtered versus unfiltered DD-Database (Table S3)
  s5_reference.tex         all 30 reference-analysis tests (Table S4)
  s6_tau.tex               fixed-tau sweep, both datasets (Table S5)
  s6_nested.tex            tau chosen in each nested fold (Table S6)
  s9_nested_fs.tex         nested choice between lean-10 and lean-7 (Table S6)
  s10_ensemble.tex         pairwise ensemble diversity (Table S7)
  s11_window.tex           calibration-window length (Table S8)
  s12_time.tex             time on task against EEG (Table S9)

Output: supplementary/tables/*.tex
"""
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common as C  # noqa: E402

OUT = os.path.join(C.R1, "supplementary", "tables")


def load(name):
    with open(os.path.join(C.RESULTS, f"{name}.json"), encoding="utf-8") as f:
        return json.load(f)


def pct(x):
    return f"{x:.1f}"


def kappa(x):
    return f"{x:.2f}".replace("-", "$-$")


def pval(x):
    if x < 0.001:
        return "{<}0.001"
    return f"{x:.3f}" if x < 0.1 else f"{x:.2f}"


def signed(x, nd=3):
    s = f"{x:+.{nd}f}"
    return s.replace("-", "$-$")


def write(name, rows):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w", encoding="utf-8", newline="\n") as f:
        f.write(f"% Generated by analysis/41_supp_tables.py. Do not edit.\n")
        f.write("\n".join(rows) + "\n")
    print("wrote", name)


def s1():
    ps = load("per_subject")["results"]
    tau = load("tau_sweep")["results"]
    for ds, short, key in (("SEED-VIG", "seed", lambda s: int(s)), ("DD-Database", "dd", lambda s: s)):
        rows = []
        per = ps[ds]["lean10"]["per_subject"]
        nested = tau[ds]["nested"]["result"]["per_subject"]
        chosen = tau[ds]["nested"]["chosen_tau_per_outer_subject"]
        for s in sorted(per, key=key):
            v = per[s]
            rows.append(" & ".join([
                s, str(v["n"]), f"{100 * v['n_drowsy'] / v['n']:.0f}", pct(v["AUC"]), pct(nested[s]["AUC"]),
                str(chosen[s]["tau"]), pct(v["F1w"]), kappa(v["kappa"]), pct(v["precision_drowsy"]),
                pct(v["recall_drowsy"]), pct(v["precision_alert"]), pct(v["recall_alert"])]) + r" \\")
        aucs = [v["AUC"] for v in per.values()]
        naucs = [nested[s]["AUC"] for s in per]
        med = lambda k: pct(np.median([v[k] for v in per.values()]))  # noqa: E731
        rows.append(r"\midrule")
        rows.append(" & ".join(["Median", "", "", pct(np.median(aucs)), pct(np.median(naucs)), "", med("F1w"),
                                kappa(np.median([v["kappa"] for v in per.values()])), med("precision_drowsy"),
                                med("recall_drowsy"), med("precision_alert"), med("recall_alert")]) + r" \\")
        write(f"s1_{short}.tex", rows)


def s3():
    g = load("sensitivity")["S3_label_grid"]
    counts = load("dd_labels")["sensitivity_grid"]
    rows = []
    for pre in (60, 120, 180):
        for gap in (300, 600, 900):
            k = f"{pre}_{gap}"
            v, c = g[k], counts[k]
            mark = r"\textbf{" if (pre, gap) == (120, 600) else "{"
            rows.append(" & ".join([mark + str(pre) + "}", mark + str(gap) + "}", f"{c['n_drowsy']:,}".replace(",", r"\,"),
                                    f"{c['n_alert']:,}".replace(",", r"\,"), str(v["n_subjects"]),
                                    pct(v["pooled_AUC"]), pct(v["subject_AUC_median"]),
                                    f"{v['subjects_AUC_above_50']}/{v['n_subjects']}"]) + r" \\")
    write("s3_grid.tex", rows)


def s4():
    u = load("sensitivity")["S4_unfiltered"]
    rows = []
    for name, v in u.items():
        label = "Band-pass 1--40~Hz (primary)" if name.startswith("filtered") else "No filtering"
        rows.append(" & ".join([label, pct(v["pooled_AUC"]), pct(v["F1w"]), pct(v["subject_AUC_median"]),
                                f"{v['subjects_AUC_above_50']}/{v['n_subjects']}"]) + r" \\")
    write("s4_filter.tex", rows)


def s5():
    r = load("reference")["results"]
    names = {"MSC O1-O2": "MSC, O1--O2", "zero-lag share O1-O2": "Zero-lag share, O1--O2",
             "ImCoh O1-O2": "ImCoh, O1--O2", "wPLI O1-O2": "wPLI, O1--O2",
             "MSC O1-O2 (common-average ref)": "MSC, O1--O2 (CAR)", "MSC C3-C4": "MSC, C3--C4",
             "MSC O1-C3": "MSC, O1--C3", "MSC O2-C4": "MSC, O2--C4", "MSC O1-C4": "MSC, O1--C4",
             "MSC O2-C3": "MSC, O2--C3"}
    rows, last = [], None
    for key in names:
        for band, sym in (("theta", r"$\theta$"), ("alpha", r"$\alpha$"), ("beta", r"$\beta$")):
            v = r[f"{key} {band}"]
            s = v["subject_level"]
            if last is not None and last != key and band == "theta":
                rows.append(r"\addlinespace[2pt]")
            last = key
            rows.append(" & ".join([names[key] if band == "theta" else "", sym, f"{v['alert_mean']:.3f}",
                                    f"{v['drowsy_mean']:.3f}", f"{s['n_increase']}/{s['n']}", pval(s["p_two_sided"]),
                                    signed(s["paired_d"], 2), pval(s["p_holm_bands"]), pval(s["p_holm_all"])]) + r" \\")
    write("s5_reference.tex", rows)


def s6():
    t = load("tau_sweep")
    rows = []
    for tau in t["taus_s"]:
        cells = ["none" if tau == 0 else str(tau)]
        for ds in ("SEED-VIG", "DD-Database"):
            v = t["results"][ds]["fixed_tau_sweep"][str(tau)]
            n = t["results"][ds]["nested"]["result"]["n_subjects"]
            cells += [pct(v["pooled"]["AUC"]), pct(v["pooled"]["F1w"]), pct(v["subject_AUC_median"]),
                      f"{v['subjects_AUC_above_50']}/{n}"]
        rows.append(" & ".join(cells) + r" \\")
    rows.append(r"\midrule")
    cells = ["Nested"]
    for ds in ("SEED-VIG", "DD-Database"):
        v = t["results"][ds]["nested"]["result"]
        cells += [pct(v["pooled"]["AUC"]), pct(v["pooled"]["F1w"]), pct(v["subject_AUC_median"]),
                  f"{v['subjects_AUC_above_50']}/{v['n_subjects']}"]
    rows.append(" & ".join(cells) + r" \\")
    write("s6_tau.tex", rows)

    rows = []
    for ds, key in (("SEED-VIG", lambda s: int(s)), ("DD-Database", lambda s: s)):
        ch = t["results"][ds]["nested"]["chosen_tau_per_outer_subject"]
        items = [f"{s}: {ch[s]['tau']}" for s in sorted(ch, key=key)]
        rows.append(ds + " & " + "; ".join(items) + r" \\")
    write("s6_nested.tex", rows)


def s9():
    v = load("sensitivity")["S9_nested_feature_set"]
    m = load("monitoring")["results"]
    rows = []
    for ds in ("SEED-VIG", "DD-Database"):
        ch = list(v[ds]["chosen_per_outer_subject"].values())
        base = m[ds]["configs"]["LDA | lean10"]
        r = v[ds]["result"]
        rows.append(" & ".join([ds, f"{ch.count('lean7')}/{len(ch)}", pct(base["pooled"]["AUC"]),
                                pct(base["subject_AUC_median"]), pct(r["pooled_AUC"]),
                                pct(r["subject_AUC_median"])]) + r" \\")
    write("s9_nested_fs.tex", rows)


def s10():
    e = load("ensemble")
    short = {"M1 lean-10 LDA": "M1", "M2 Riemannian TS+LDA": "M2", "M3 EMA (nested tau)": "M3"}
    rows = []
    for name, v in e["pairs"].items():
        a, b = name.split(" ~ ")
        rows.append(" & ".join([f"{short[a]}--{short[b]}", kappa(v["posterior_r"]),
                                kappa(v["posterior_r_within_subject_median"]), kappa(v["error_r"]), kappa(v["yules_Q"]),
                                pct(100 * v["disagreement"]), pct(100 * v["double_fault"])]) + r" \\")
    write("s10_ensemble.tex", rows)


def s11():
    w = load("cross_dataset")["calibration_window_sensitivity"]
    rows = []
    for label, what, varied in (("SEED-VIG, LOSO", "SEED-VIG LOSO", "SEED-VIG"),
                                ("DD-Database, LOSO", "DD-Database LOSO", "DD-Database"),
                                ("DD-Database $\\rightarrow$ SEED-VIG", "DD-Database -> SEED-VIG", "DD-Database"),
                                ("", "DD-Database -> SEED-VIG", "SEED-VIG"),
                                ("SEED-VIG $\\rightarrow$ DD-Database", "SEED-VIG -> DD-Database", "DD-Database"),
                                ("", "SEED-VIG -> DD-Database", "SEED-VIG")):
        cells = [label, varied]
        for sec in (60, 120, 300):
            v = w[f"{what} | {varied} window {sec} s"]
            cells += [pct(v["pooled_AUC"]), pct(v["subject_AUC_median"])]
        rows.append(" & ".join(cells) + r" \\")
    write("s11_window.tex", rows)


def s12():
    a = load("alarms")
    rows = []
    for ds in ("SEED-VIG", "DD-Database"):
        s = a[ds]["time_on_task"]["summary"]
        rows.append(" & ".join([ds, str(s["n"]), pct(s["time"]), pct(s["eeg"]), pct(s["eeg_ema"]),
                                f"{s['eeg_beats_time']}/{s['n']}", pval(s["eeg_vs_time"]["p_two_sided"]),
                                f"{s['eeg_ema_beats_time']}/{s['n']}", pval(s["eeg_ema_vs_time"]["p_two_sided"])]) + r" \\")
    write("s12_time.tex", rows)


if __name__ == "__main__":
    s1()
